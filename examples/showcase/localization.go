package main

import (
	"strconv"
	"strings"

	"github.com/qianniancn/flowui/window"
)

func (m Model) text(value string) string { return m.demo.text(value) }

func (m demoState) text(value string) string {
	if m.language == window.LanguageEnglish {
		if translated, ok := englishText[value]; ok {
			return translated
		}
	}
	return value
}

func (item entry) localized(m demoState) entry {
	if m.language == window.LanguageEnglish {
		item.title = m.text(item.title)
	} else if _, title, ok := strings.Cut(item.title, " · "); ok {
		item.title = title
	}
	item.group = m.text(item.group)
	item.summary = m.text(item.summary)
	// Code samples contain Go string literals and comments, not nested UI widgets.
	item.code = localizeCode(item.code, m)
	return item
}

func localizeCode(source string, m demoState) string {
	if m.language == window.LanguageEnglish {
		return englishCode.Replace(source)
	}
	return source
}

var englishCode = func() *strings.Replacer {
	pairs := []string{}
	for original, translated := range englishText {
		pairs = append(pairs, strconv.Quote(original), strconv.Quote(translated))
	}
	return strings.NewReplacer(pairs...)
}()

